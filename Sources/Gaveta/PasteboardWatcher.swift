import AppKit

/// Puts images copied to the clipboard in the drawer too, like a screenshot
/// taken with Control held or an image copied in a browser. Each one is
/// saved as a PNG in Gaveta's folder, so it behaves like any capture.
///
/// The clipboard has no change notification, so its change count is read
/// twice a second; the contents are only read when the change count moves.
@MainActor
final class PasteboardWatcher {
    private let onImage: (URL) -> Void
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    /// Some apps put the same image on the clipboard again; it goes in once.
    private var lastSaved: (png: Data, url: URL)?

    /// Copies that carry a picture without being one: text from a document
    /// comes with an image of itself, a file from Finder with its icon, and
    /// a capture copied from the drawer with its file. Password managers
    /// mark private and passing copies (nspasteboard.org).
    private static let skipped: Set<NSPasteboard.PasteboardType> = [
        .string, .fileURL, .URL, .rtf, .html,
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
    private static let maxBytes = 60 * 1024 * 1024

    init(onImage: @escaping (URL) -> Void) {
        self.onImage = onImage
    }

    func start() {
        guard timer == nil else { return }
        // What is on the clipboard already is not new.
        lastChange = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let board = NSPasteboard.general
        let change = board.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard let items = board.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ Self.skipped.isDisjoint(with: $0.types) }),
              let type = board.availableType(from: [.png, .tiff]),
              let data = board.data(forType: type), data.count <= Self.maxBytes else { return }
        // Decoding a big image takes a moment, so it happens off the main thread.
        Task.detached(priority: .userInitiated) {
            let png = type == .png ? data : NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
            await MainActor.run {
                // Copied over again meanwhile: the newer copy is the one that counts.
                guard let png, NSPasteboard.general.changeCount == change else { return }
                self.save(png)
            }
        }
    }

    private func save(_ png: Data) {
        if let lastSaved, lastSaved.png == png, FileManager.default.fileExists(atPath: lastSaved.url.path) { return }
        let folder = CaptureTakeover.folder
        let url = Self.uniqueURL(in: folder)
        do {
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            try png.write(to: url, options: .atomic)
            // What people copy can be private: only they can read it.
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            lastSaved = (png, url)
            onImage(url)
        } catch {
            try? FileManager.default.removeItem(at: url)
        }
    }

    /// An image the watcher saved from the clipboard, in either language.
    nonisolated static func isCopiedImage(_ url: URL) -> Bool {
        let name = url.lastPathComponent
        return name.hasPrefix("Imagem copiada") || name.hasPrefix("Copied image")
    }

    private static func uniqueURL(in folder: URL) -> URL {
        let formatter = DateFormatter()
        formatter.locale = Language.locale
        formatter.dateFormat = Language.isPortuguese ? "yyyy-MM-dd 'às' HH.mm.ss" : "yyyy-MM-dd 'at' HH.mm.ss"
        let base = "\(tr("Imagem copiada", "Copied image")) \(formatter.string(from: Date()))"
        var url = folder.appendingPathComponent(base).appendingPathExtension("png")
        var n = 2
        while FileManager.default.fileExists(atPath: url.path) {
            url = folder.appendingPathComponent("\(base) \(n)").appendingPathExtension("png")
            n += 1
        }
        return url
    }
}
